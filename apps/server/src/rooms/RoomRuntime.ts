  /**
   * Lets every listed test player make one plain legal move, each computed from that player's
   * own view and sent through the normal command path (same checks as a real client).
   */
  async autoplay(
    playerIds: PlayerId[],
  ): Promise<{ playerId: PlayerId; action: string; ok: boolean; error?: string }[]> {
    const done: { playerId: PlayerId; action: string; ok: boolean; error?: string }[] = [];
    for (const playerId of playerIds) {
      const seg = this.segment;
      if (seg?.status !== "active" || !this.members.has(playerId)) continue;
      const action = botAction(seg.gameId, seg.module.view(seg.state, playerId), playerId);
      if (!action) continue;
      const ack = await this.handleCommand(playerId, {
        cmdId: newId("bot"),
        command: { type: "gameAction", segmentId: seg.id, action },
      });
      done.push({ playerId, action: String(action.type), ok: ack.ok, ...(ack.ok ? {} : { error: ack.error }) });
    }
    return done;
  }

