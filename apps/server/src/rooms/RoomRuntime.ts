  suggestGame(gameId: string, reason: string): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const module = games[gameId];
      if (!module) return { ok: false, message: `失败：没有 id 为 ${gameId} 的已实现游戏。` };
      // Checked against the latest state at execution time, not when the model was called.
      if (this.segment) return { ok: false, message: "失败：有游戏正在进行，现在不能发起推荐。" };
      this.suggestion = { gameId, reason };
      this.broadcast();
      return { ok: true, message: `已在主面板展示「${module.meta.name}」的推荐，等待房主决定是否开始（尚未开始）。` };
    });
  }

  createInteraction(spec: AgentInteractionSpec): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const members = [...this.members.keys()];
      if (spec.kind !== "show" && respondersOf(spec, members).length === 0) {
        return { ok: false, message: "失败：指定的回应者都不在房间里（audience 要用成员 id）。" };
      }
      const live = await this.enqueueInteraction(spec, "agent");
      const state =
        live.status === "queued"
          ? "已排队，会在当前回合结束后的间隙显示"
          : spec.kind === "show"
            ? "已展示在主面板"
            : "已显示在主面板，正在等玩家回应";
      return {
        ok: true,
        message: `${state}。${spec.kind === "show" ? "" : "玩家回应完（或房主收尾）后你会收到结果，现在不需要等待。"}`,
      };
    });
  }

  async saveContent(type: string, theme: string, payloads: unknown[]): Promise<{ ok: boolean; message: string }> {
    const { saved, rejected } = await this.deps.content.save(
      this.deps.db,
      payloads.map((payload) => ({ type, theme, payload })),
      `AI 生成（${this.deps.agent.modelLabel}）`,
    );
    const parts = [
      saved.length > 0 ? `已保存 ${saved.length} 条，id：${saved.map((i) => i.id).join(", ")}` : "没有保存任何内容",
      ...rejected,
    ];
    return { ok: saved.length > 0, message: parts.join("。") };
  }

  /**
   * Hands AI-written content to the game. It becomes the current candidates only while the topic
   * is being chosen AND the request came from the picker (or the host, or a flow the room agreed
   * on); otherwise it is kept in the party's candidate history for a picker to take. A topic that
   * is already confirmed is never replaced.
   */
  offerContent(ids: string[], requester: PlayerId | null = null): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const seg = this.segment;
      if (!seg) return { ok: false, message: "失败：现在没有进行中的游戏，候选内容只能交给进行中的游戏。" };
      if (seg.status === "paused") return { ok: false, message: "失败：游戏已暂停。" };
      const type = seg.module.meta.contentType;
      if (!seg.module.offer || !type) {
        return { ok: false, message: `失败：「${seg.module.meta.name}」不接受外部候选内容。` };
      }
      const items = (await this.deps.content.getByIds(ids)).filter((i) => i.type === type);
      if (items.length === 0) return { ok: false, message: `失败：题库里找不到这些 id，或它们不是 ${type} 类型。` };
      const picker = pickerOf(seg.state);
      const direct = picker !== null && (requester === null || requester === picker || requester === this.hostPlayerId);
      const viewers = (seg.state as { pick?: { viewers?: PlayerId[] | null } }).pick?.viewers ?? null;
      const made = this.makeContext(seg);
      if (direct) {
        const result = seg.module.offer(structuredClone(seg.state), items, made.ctx);
        if (!result.ok) return { ok: false, message: `失败：${result.error}` };
        for (const item of items) {
          seg.offered.set(item.id, item);
          made.shown.push({ item, viewers });
        }
        const ack = await this.commit(seg, result, made);
        this.logEvent("content.offer", requester, { count: items.length, applied: true });
        return ack.ok
          ? { ok: true, message: result.message ?? "已交给游戏" }
          : { ok: false, message: `失败：${ack.error}` };
      }
      // Not applied: nobody has seen these yet, so a secret item is still usable by any picker.
      const records: CandidateRecord[] = items
        .filter((item) => !seg.history.has(item.id))
        .map((item) => ({ item, status: "shown", seenBy: viewers === null ? null : [], origin: "ai" }));
      await this.deps.content.recordCandidates(this.deps.db, this.sessionId, records);
      for (const r of records) {
        seg.history.set(r.item.id, r);
        seg.offered.set(r.item.id, r.item);
      }
      this.logEvent("content.offer", requester, { count: items.length, applied: false });
      return {
        ok: true,
        message:
          picker !== null
            ? `未直接替换候选：这一轮由 ${this.members.get(picker)?.nickname ?? "题主"} 选题。已把 ${items.length} 道放进左侧「历史候选」，由 TA 决定是否采用。`
            : `未应用：这一轮的题目已经确定，不会被替换。已把 ${items.length} 道保存到本场「历史候选」，之后选题的人可以选用。`,
      };
    });
  }

  proposeStartGame(
    gameId: string,
    config: Record<string, number>,
    reason: string,
  ): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const module = games[gameId];
      if (!module) return { ok: false, message: `失败：没有 id 为 ${gameId} 的已实现游戏。` };
      const parsed = module.configSchema.safeParse(config);
      if (!parsed.success) return { ok: false, message: "失败：设置项无效（只能用该游戏列出的设置键和范围）。" };
      await this.enqueueInteraction(
        {
          kind: "confirm",
          title: `开始「${module.meta.name}」？`,
          description: reason.slice(0, 200),
          audience: [this.hostPlayerId],
          effect: { type: "startGame", gameId, config },
        },
        "agent",
      );
      return { ok: true, message: "已向房主发出确认请求（尚未开始）。房主决定后你会收到结果。" };
    });
  }

  /** Agent tool: a proposal the host can approve. `requester` is recorded as who asked for it. */
  proposeAdjustment(
    items: { playerId: string; points: number }[],
    reason: string,
    requester: PlayerId | null = null,
  ): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const made = await this.createAdjustment(items, reason, "agent");
      if (made.ok && requester) this.logEvent("party.adjust-requested", requester);
      return made.ok ? made : { ok: false, message: `失败：${made.message}` };
    });
  }

  private prefsText(): string {
    const p = this.prefs;
    const parts = [
      p.familiar && `大家熟悉：${p.familiar}`,
      p.want && `今天想玩：${p.want}`,
      p.avoid && `不要出现：${p.avoid}`,
      p.difficulty !== "normal" && `难度：${p.difficulty === "easy" ? "轻松" : "有挑战"}`,
      p.suggestions.length > 0 &&
        `成员的建议：${p.suggestions.map((x) => `${this.nameOf(x.playerId)}「${x.text}」`).join("；")}`,
    ].filter(Boolean);
    return parts.length > 0 ? `本场偏好——${parts.join("；")}` : "本场偏好：还没有设置。";
  }

  async setNote(text: string): Promise<void> {
    this.agentNote = text.slice(0, 600) || null;
    await this.deps.db.update(rooms).set({ agentNote: this.agentNote }).where(eq(rooms.id, this.roomId));
  }

  postChat(kind: "agent" | "system", text: string): Promise<void> {
    return this.appendChat({ kind }, text);
  }

  setAiStatus(status: AiStatus) {
    this.aiStatus = status;
    this.broadcast();
  }
