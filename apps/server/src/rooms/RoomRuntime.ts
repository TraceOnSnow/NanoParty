  private scoreboard(): ScoreEntry[] {
    return [...this.members.keys()]
      .map((playerId) => ({
        playerId,
        points: this.scoring === "rank-v1" ? (this.tenths.get(playerId) ?? 0) / 10 : (this.scores.get(playerId) ?? 0),
      }))
      .sort((a, b) => b.points - a.points);
  }

  private viewFor(playerId: PlayerId): RoomView {
    const isHost = playerId === this.hostPlayerId;
    const seg = this.segment;
    return {
      room: { id: this.roomId, name: this.roomName },
      me: { playerId, isHost },
      ...(isHost ? { inviteToken: this.inviteToken } : {}),
      members: [...this.members.values()].map((m) => ({
        id: m.id,
        nickname: m.nickname,
        isHost: m.id === this.hostPlayerId,
        connected: this.isConnected(m.id),
      })),
      sessionId: this.sessionId,
      scoreboard: this.scoreboard(),
      games: Object.values(games).map((g) => g.meta),
      segment: seg
        ? {
            id: seg.id,
            gameId: seg.gameId,
            status: seg.status,
            view: seg.module.view(seg.state, playerId),
            skip: this.skipViewFor(seg, playerId),
            rawScores: [...this.segmentRaw.entries()]
              .map(([p, points]) => ({ playerId: p, points }))
              .sort((a, b) => b.points - a.points),
            contentId: seg.module.currentContentId?.(seg.state) ?? null,
            notice: this.segmentNotice,
          }
        : null,
      lastSegment: this.lastSegment,
      party: { sessionId: this.sessionId, scoring: this.scoring, ...this.party },
      prefs: this.prefs,
      settlement: this.settlement
        ? {
            segmentId: this.settlement.segmentId,
            gameId: this.settlement.gameId,
            gameName: games[this.settlement.gameId]?.meta.name ?? this.settlement.gameId,
            endedReason: this.settlement.endedReason,
            rows: this.settlement.rows,
            note: this.settlement.note,
          }
        : null,
      adjustments: this.pending.map((a): AdjustmentView => toAdjustmentView(a, (id) => this.nameOf(id))),
      suggestion: this.suggestion,
      ai: this.aiStatus,
      canvas: {
        current: this.canvasCurrent
          ? toView(
              this.canvasCurrent,
              playerId,
              [...this.members.keys()],
              this.canvasCurrent.spec.kind === "confirm"
                ? this.describeEffect(this.canvasCurrent.spec.effect)
                : undefined,
            )
          : null,
        queued: this.canvasQueue.length,
      },
    };
  }

  private skipViewFor(seg: LiveSegment, playerId: PlayerId): SegmentView["skip"] {
    const key = seg.status === "active" ? (seg.module.skip?.key(seg.state) ?? null) : null;
    if (!seg.module.skip || key === null) return null;
    // Votes cast for an earlier item never carry over.
    const vote = this.skipVote?.key === key ? this.skipVote : null;
    const voters = vote?.voters ?? seg.module.skip.voters(seg.state);
    return {
      key,
      votes: vote?.votes.size ?? 0,
      needed: Math.floor(voters.length / 2) + 1,
      canVote: voters.includes(playerId),
      voted: vote?.votes.has(playerId) ?? false,
    };
  }

  private broadcast() {
    for (const c of this.connections.values()) c.send(MSG.view, this.viewFor(c.playerId));
  }

