// biome-ignore lint/suspicious/noExplicitAny: per-game generics are erased at the runtime boundary
type AnyGame = GameModule<any, any, any, any>;

interface LiveSegment {
  id: string;
  gameId: string;
  module: AnyGame;
  status: "active" | "paused";
  state: unknown;
  /** Unused content for this segment; `drawContent` pops from here. */
  pool: ContentItem[];
  /** Content offered from outside the pool (e.g. generated by the AI host), by id. */
  offered: Map<string, ContentItem>;
  /** This party's candidate history for the game's content type, by content id (oldest first). */
  history: Map<string, CandidateRecord>;
}

interface Drawn {
  ctx: GameContext;
  /** Content used up by this step. */
  drawn: ContentItem[];
  /** Candidates put in front of players by this step, with who may see them. */
  shown: { item: ContentItem; viewers: PlayerId[] | null }[];
}

/** Who is choosing the topic right now, if the game is in its pick phase. */
function pickerOf(state: unknown): PlayerId | null {
  const s = state as { phase?: string; pick?: { picker?: string }; giver?: string } | null;
  if (s?.phase !== "pick") return null;
  return s.pick?.picker ?? s.giver ?? null;
}

