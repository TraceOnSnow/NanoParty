/**
 * Authoritative runtime of one room. Transport-agnostic: Colyseus (or a test) feeds it
 * authenticated connections and messages; it owns members, chat, the party session,
 * the current game segment, timers and the scoreboard.
 *
 * Invariants:
 * - All mutations run one at a time through `exclusive()`.
 * - State is persisted in one transaction BEFORE memory is updated and views are sent,
 *   so anything a client has seen survives a restart.
 * - Clients only ever receive `view(state, player)`; raw game state never leaves this class.
 */
import { contentTypes, games } from "@apr/games";
import {
  type Ack,
  type AgentInteractionSpec,
  type AiStatus,
  type CanvasEffect,
  type ChatMessageView,
  type Command,
  type CommandEnvelope,
  type ContentItem,
  type GameContext,
  type GameModule,
  type GameResult,
  type InteractionSpec,
  type LastSegmentView,
  MSG,
  type PlayerId,
  type RoomView,
  type ScoreEntry,
  type SegmentView,
} from "@apr/shared";
import { and, asc, desc, eq, inArray, isNull, sql } from "drizzle-orm";
import type { AgentRoomContext, AgentRoomPort, AgentService } from "../agent/AgentService.ts";
import type { ContentService } from "../content/ContentService.ts";
import type { Db } from "../db/client.ts";
import { chatMessages, interactions, partySessions, players, rooms, scoreEvents, segments } from "../db/schema.ts";
import { RateLimiter } from "../util/rateLimit.ts";
import { newId, randomToken, sha256 } from "../util/tokens.ts";
import { computeResult, type LiveInteraction, respondersOf, summarize, toView, validateResponse } from "./canvas.ts";

export interface RuntimeDeps {
  db: Db;
  content: ContentService;
  agent: AgentService;
  now?: () => number;
  random?: () => number;
}

export type Send = (type: string, payload: unknown) => void;

// biome-ignore lint/suspicious/noExplicitAny: per-game generics are erased at the runtime boundary
type AnyGame = GameModule<any, any, any, any>;

interface LiveSegment {
  id: string;
  gameId: string;
  module: AnyGame;
  status: "active" | "paused";
  state: unknown;
  /** Unused content for this segment; `drawContent` pops from here. */
  pool: ContentItem[];
  /** Content offered from outside the pool (e.g. generated by the AI host), by id. */
  offered: Map<string, ContentItem>;
}

const CHAT_HISTORY = 100;
const AGENT_CHAT_CONTEXT = 20;
const AI_MENTION = /@(ai|主持)/i;
const MAX_CACHED_COMMANDS = 500;

export class RoomRuntime implements AgentRoomPort {
  private queue: Promise<unknown> = Promise.resolve();
  private readonly connections = new Map<number, { playerId: PlayerId; send: Send; close?: () => void }>();
  private nextConnId = 1;
  private readonly members = new Map<PlayerId, { id: PlayerId; nickname: string }>();
  private readonly scores = new Map<PlayerId, number>();
  private chat: ChatMessageView[] = [];
  private segment: LiveSegment | null = null;
  private lastSegment: LastSegmentView | null = null;
  private suggestion: { gameId: string; reason: string } | null = null;
  private aiStatus: AiStatus;
  private timer: NodeJS.Timeout | null = null;
  private readonly commandResults = new Map<string, Promise<Ack>>();
  private readonly chatLimiter = new RateLimiter(8, 10_000);
  private disposed = false;
  /** In-progress vote to skip the current item. Bound to the item's key; voters are fixed when it opens. */
  /** Canvas interactions waiting for a safe point, oldest first. */
  private canvasQueue: LiveInteraction[] = [];
  /** The interaction on screen: open, or the last closed one until dismissed or replaced. */
  private canvasCurrent: LiveInteraction | null = null;
  private agentNote: string | null = null;
  private skipVote: { key: string; voters: PlayerId[]; votes: Set<PlayerId> } | null = null;

  private constructor(
    private readonly deps: RuntimeDeps,
    readonly roomId: string,
    private readonly roomName: string,
    private inviteToken: string,
    private readonly hostPlayerId: PlayerId,
    private sessionId: string,
  ) {
    this.aiStatus = deps.agent.initialStatus();
  }

  // ---------------------------------------------------------------- loading

  /** Rebuilds the runtime from the database. Returns null if the room does not exist. */
  static async load(deps: RuntimeDeps, roomId: string): Promise<RoomRuntime | null> {
    const { db } = deps;
    const [room] = await db.select().from(rooms).where(eq(rooms.id, roomId));
    if (!room) return null;

    let [session] = await db
      .select()
      .from(partySessions)
      .where(and(eq(partySessions.roomId, roomId), eq(partySessions.status, "active")));
    if (!session) {
      [session] = await db
        .insert(partySessions)
        .values({ id: newId("ses"), roomId, status: "active" })
        .returning();
    }
    if (!session) throw new Error("failed to open party session");

    const rt = new RoomRuntime(deps, room.id, room.name, room.inviteToken, room.hostPlayerId, session.id);

    for (const p of await db
      .select()
      .from(players)
      .where(and(eq(players.roomId, roomId), isNull(players.removedAt)))
      .orderBy(asc(players.createdAt))) {
      rt.members.set(p.id, { id: p.id, nickname: p.nickname });
    }

    const totals = await db
      .select({ playerId: scoreEvents.playerId, points: sql<number>`sum(${scoreEvents.points})::int` })
      .from(scoreEvents)
      .where(eq(scoreEvents.sessionId, session.id))
      .groupBy(scoreEvents.playerId);
    for (const t of totals) rt.scores.set(t.playerId, t.points);

    const history = await db
      .select()
      .from(chatMessages)
      .where(eq(chatMessages.roomId, roomId))
      .orderBy(desc(chatMessages.createdAt))
      .limit(CHAT_HISTORY);
    rt.chat = history.reverse().map((m) => rt.toChatView(m));

    const [seg] = await db
      .select()
      .from(segments)
      .where(and(eq(segments.sessionId, session.id), inArray(segments.status, ["active", "paused"])));
    if (seg) {
      const module = games[seg.gameId];
      if (module) {
        // A segment found on load was interrupted by a restart: it waits for the host to resume,
        // so downtime never counts as a player timeout and no timer fires unattended.
        if (seg.status === "active") {
          await db.update(segments).set({ status: "paused" }).where(eq(segments.id, seg.id));
        }
        const pool = module.meta.contentType ? await deps.content.pool(module.meta.contentType, session.id) : [];
        rt.segment = {
          id: seg.id,
          gameId: seg.gameId,
          module,
          status: "paused",
          state: seg.state,
          pool,
          offered: new Map(),
        };
      } else {
        // The game module no longer exists in this build; close the segment, keep its scores.
        await db.update(segments).set({ status: "aborted", endedAt: new Date() }).where(eq(segments.id, seg.id));
      }
    }
    rt.agentNote = room.agentNote;
    const pending = await db
      .select()
      .from(interactions)
      .where(and(eq(interactions.roomId, roomId), inArray(interactions.status, ["queued", "open"])))
      .orderBy(asc(interactions.createdAt));
    for (const row of pending) {
      const live: LiveInteraction = {
        id: row.id,
        spec: row.spec as InteractionSpec,
        status: row.status === "open" ? "open" : "queued",
        responses: row.responses as LiveInteraction["responses"],
        result: null,
        createdBy: row.createdBy,
      };
      if (live.status === "open" && !rt.canvasCurrent) rt.canvasCurrent = live;
      else rt.canvasQueue.push({ ...live, status: "queued" });
    }
    return rt;
  }

  dispose() {
    this.disposed = true;
    if (this.timer) clearTimeout(this.timer);
  }

  // ------------------------------------------------------------ connections

  /** Resolves a session token to a player of this room. Nicknames play no part in identity. */
  async authenticate(sessionToken: unknown): Promise<PlayerId | null> {
    if (typeof sessionToken !== "string" || sessionToken.length < 16) return null;
    const [player] = await this.deps.db
      .select()
      .from(players)
      .where(
        and(
          eq(players.sessionTokenHash, sha256(sessionToken)),
          eq(players.roomId, this.roomId),
          isNull(players.removedAt),
        ),
      );
    if (!player) return null;
    if (!this.members.has(player.id)) {
      this.members.set(player.id, { id: player.id, nickname: player.nickname });
    }
    return player.id;
  }

  /** Registers a live connection and sends it the full snapshot. Returns the disconnect function. */
  connect(playerId: PlayerId, send: Send, close?: () => void): () => void {
    const connId = this.nextConnId++;
    this.connections.set(connId, { playerId, send, close });
    send(MSG.chatHistory, this.chat);
    this.broadcast();
    return () => {
      if (this.connections.delete(connId)) this.broadcast();
    };
  }

  private isConnected(playerId: PlayerId): boolean {
    for (const c of this.connections.values()) if (c.playerId === playerId) return true;
    return false;
  }

  // ------------------------------------------------------------------- chat

  async handleChat(playerId: PlayerId, text: string): Promise<Ack> {
    const member = this.members.get(playerId);
    if (!member) return { ok: false, error: "未加入房间" };
    if (!this.chatLimiter.take(playerId)) return { ok: false, error: "发送太快了，请稍等" };
    await this.appendChat({ kind: "player", playerId }, text);
    // Plain chat is stored but never calls the model; only an explicit mention does.
    if (AI_MENTION.test(text)) {
      this.deps.agent.trigger(this, { kind: "mention", nickname: member.nickname, text });
    }
    return { ok: true };
  }

  private async appendChat(
    sender: { kind: "player"; playerId: PlayerId } | { kind: "agent" } | { kind: "system" },
    text: string,
  ): Promise<void> {
    const [row] = await this.deps.db
      .insert(chatMessages)
      .values({
        id: newId("msg"),
        roomId: this.roomId,
        senderKind: sender.kind,
        playerId: sender.kind === "player" ? sender.playerId : null,
        text,
      })
      .returning();
    if (!row) return;
    const view = this.toChatView(row);
    this.chat.push(view);
    if (this.chat.length > CHAT_HISTORY) this.chat.shift();
    for (const c of this.connections.values()) c.send(MSG.chatMessage, view);
  }

  private toChatView(row: typeof chatMessages.$inferSelect): ChatMessageView {
    const sender: ChatMessageView["sender"] =
      row.senderKind === "player" && row.playerId
        ? { kind: "player", playerId: row.playerId, nickname: this.members.get(row.playerId)?.nickname ?? "?" }
        : row.senderKind === "agent"
          ? { kind: "agent" }
          : { kind: "system" };
    return { id: row.id, sender, text: row.text, createdAt: row.createdAt.getTime() };
  }

  // --------------------------------------------------------------- commands

  /** Entry point for every formal operation. Re-sending the same cmdId never executes twice. */
  handleCommand(playerId: PlayerId, envelope: CommandEnvelope): Promise<Ack> {
    const key = `${playerId}:${envelope.cmdId}`;
    const cached = this.commandResults.get(key);
    if (cached) return cached;
    const result = this.exclusive(() => this.execute(playerId, envelope.command)).catch((err): Ack => {
      console.error(`[room ${this.roomId}] command ${envelope.command.type} failed:`, err);
      return { ok: false, error: "服务器内部错误，操作未生效" };
    });
    this.commandResults.set(key, result);
    if (this.commandResults.size > MAX_CACHED_COMMANDS) {
      const oldest = this.commandResults.keys().next().value;
      if (oldest) this.commandResults.delete(oldest);
    }
    return result;
  }

  private exclusive<T>(fn: () => Promise<T>): Promise<T> {
    const run = this.queue.then(fn, fn);
    this.queue = run.catch(() => {});
    return run;
  }

  private async execute(playerId: PlayerId, command: Command): Promise<Ack> {
    const member = this.members.get(playerId);
    if (!member) return { ok: false, error: "未加入房间" };
    const isHost = playerId === this.hostPlayerId;

    switch (command.type) {
      case "startGame": {
        if (!isHost) return { ok: false, error: "只有房主可以开始游戏" };
        return this.startGame(command.gameId, command.config);
      }
      case "gameAction": {
        const seg = this.segment;
        if (!seg || seg.id !== command.segmentId) return { ok: false, error: "这局游戏已经结束" };
        if (seg.status === "paused") return { ok: false, error: "游戏已暂停，等待房主恢复" };
        const action = seg.module.actionSchema.safeParse(command.action);
        if (!action.success) return { ok: false, error: "无效的操作" };
        const { ctx, drawn } = this.makeContext(seg.pool, seg.offered);
        const result = seg.module.apply(
          structuredClone(seg.state),
          action.data,
          { kind: "player", playerId, isHost },
          ctx,
        );
        return this.commit(seg, result, drawn);
      }
      case "endSegment": {
        if (!isHost) return { ok: false, error: "只有房主可以结束当前游戏" };
        const seg = this.segment;
        if (!seg || seg.id !== command.segmentId) return { ok: false, error: "这局游戏已经结束" };
        await this.deps.db
          .update(segments)
          .set({ status: "aborted", endedAt: new Date() })
          .where(eq(segments.id, seg.id));
        await this.closeSegment(seg, "aborted");
        return { ok: true };
      }
      case "resumeSegment": {
        if (!isHost) return { ok: false, error: "只有房主可以恢复游戏" };
        const seg = this.segment;
        if (!seg || seg.id !== command.segmentId) return { ok: false, error: "这局游戏已经结束" };
        if (seg.status !== "paused") return { ok: true };
        const { ctx } = this.makeContext(seg.pool, seg.offered);
        const state = seg.module.onResume?.(structuredClone(seg.state), ctx) ?? seg.state;
        await this.deps.db.update(segments).set({ status: "active", state }).where(eq(segments.id, seg.id));
        seg.state = state;
        seg.status = "active";
        this.scheduleDeadline();
        await this.pumpCanvas();
        this.broadcast();
        return { ok: true };
      }
      case "askAgent": {
        const queued = this.deps.agent.trigger(this, { kind: "recommend", nickname: member.nickname });
        return queued ? { ok: true } : { ok: false, error: "AI 主持未启用，请直接选择游戏" };
      }
      case "dismissSuggestion": {
        if (!isHost) return { ok: false, error: "只有房主可以处理建议" };
        this.suggestion = null;
        this.broadcast();
        return { ok: true };
      }
      case "voteSkip": {
        const seg = this.segment;
        if (!seg || seg.id !== command.segmentId) return { ok: false, error: "这局游戏已经结束" };
        if (seg.status === "paused") return { ok: false, error: "游戏已暂停，等待房主恢复" };
        const key = seg.module.skip?.key(seg.state) ?? null;
        // The vote is for the item the player was looking at; if that item is gone, so is the vote.
        if (!seg.module.skip || key === null || key !== command.key) return { ok: false, error: "这一题已经过去了" };
        if (this.skipVote?.key !== key) {
          this.skipVote = { key, voters: [...seg.module.skip.voters(seg.state)], votes: new Set() };
        }
        if (!this.skipVote.voters.includes(playerId)) return { ok: false, error: "只有参与本题的玩家可以投票" };
        this.skipVote.votes.add(playerId);
        // Strict majority of the players who were in when the vote opened.
        if (this.skipVote.votes.size * 2 <= this.skipVote.voters.length) {
          this.broadcast();
          return { ok: true };
        }
        this.skipVote = null;
        const { ctx, drawn } = this.makeContext(seg.pool, seg.offered);
        return this.commit(seg, seg.module.skip.apply(structuredClone(seg.state), ctx), drawn);
      }
      case "contentFeedback": {
        const seg = this.segment;
        if (!seg || seg.id !== command.segmentId) return { ok: false, error: "这局游戏已经结束" };
        if (seg.module.currentContentId?.(seg.state) !== command.contentId) {
          return { ok: false, error: "这一题已经过去了" };
        }
        await this.deps.content.recordFeedback(this.sessionId, command.contentId, playerId, command.kind);
        return { ok: true };
      }
      case "endSession": {
        if (!isHost) return { ok: false, error: "只有房主可以结束本场聚会" };
        if (this.segment) return { ok: false, error: "请先结束当前游戏" };
        const summary = this.scoreboard()
          .filter((s) => s.points > 0)
          .map((s) => `${this.members.get(s.playerId)?.nickname ?? "?"} ${s.points} 分`)
          .join("，");
        const next = newId("ses");
        await this.deps.db.transaction(async (tx) => {
          await tx
            .update(partySessions)
            .set({ status: "ended", endedAt: new Date() })
            .where(eq(partySessions.id, this.sessionId));
          await tx.insert(partySessions).values({ id: next, roomId: this.roomId, status: "active" });
        });
        this.sessionId = next;
        this.scores.clear();
        this.lastSegment = null;
        this.suggestion = null;
        await this.appendChat(
          { kind: "system" },
          `本场聚会结束。最终成绩：${summary || "没有人得分"}。新的一场从零开始。`,
        );
        this.broadcast();
        return { ok: true };
      }
      case "rotateInvite": {
        if (!isHost) return { ok: false, error: "只有房主可以更换邀请链接" };
        const token = randomToken();
        await this.deps.db.update(rooms).set({ inviteToken: token }).where(eq(rooms.id, this.roomId));
        // The old link stops admitting new players; people already in the room are unaffected.
        this.inviteToken = token;
        this.broadcast();
        return { ok: true };
      }
      case "respond": {
        const live = this.canvasCurrent;
        if (!live || live.id !== command.interactionId || live.status !== "open") {
          return { ok: false, error: "这个互动已经结束了" };
        }
        const responders = respondersOf(live.spec, [...this.members.keys()]);
        if (!responders.includes(playerId)) return { ok: false, error: "这个互动不需要你回应" };
        if (playerId in live.responses) return { ok: false, error: "你已经提交过了" };
        const checked = validateResponse(live.spec, command.value);
        if (!checked.ok) return { ok: false, error: checked.error };
        const responses = { ...live.responses, [playerId]: checked.value };
        await this.deps.db.update(interactions).set({ responses }).where(eq(interactions.id, live.id));
        live.responses = responses;
        if (responders.every((p) => p in live.responses)) await this.closeInteraction(live);
        else this.broadcast();
        return { ok: true };
      }
      case "closeInteraction": {
        if (!isHost) return { ok: false, error: "只有房主可以收尾或关闭互动" };
        const live = this.canvasCurrent;
        if (!live || live.id !== command.interactionId) return { ok: false, error: "这个互动已经不在屏幕上了" };
        if (live.status === "open") {
          // Stop waiting: whatever has been received is the result.
          await this.closeInteraction(live);
        } else {
          this.canvasCurrent = null;
          await this.pumpCanvas();
          this.broadcast();
        }
        return { ok: true };
      }
      case "removeMember": {
        if (!isHost) return { ok: false, error: "只有房主可以移除成员" };
        if (command.playerId === this.hostPlayerId) return { ok: false, error: "不能移除房主" };
        if (this.segment) return { ok: false, error: "请在大厅（没有进行中的游戏）时移除成员" };
        const target = this.members.get(command.playerId);
        if (!target) return { ok: false, error: "该成员不在房间里" };
        await this.deps.db.update(players).set({ removedAt: new Date() }).where(eq(players.id, target.id));
        this.members.delete(target.id);
        for (const [id, c] of this.connections) {
          if (c.playerId !== target.id) continue;
          this.connections.delete(id);
          c.close?.();
        }
        await this.appendChat({ kind: "system" }, `${target.nickname} 已被房主移出房间。`);
        this.broadcast();
        return { ok: true };
      }
    }
  }

  private async startGame(gameId: string, rawConfig: unknown): Promise<Ack> {
    if (this.segment) return { ok: false, error: "已有游戏在进行中" };
    const module = games[gameId];
    if (!module) return { ok: false, error: "未知的游戏" };
    const count = this.members.size;
    if (count < module.meta.minPlayers || count > module.meta.maxPlayers) {
      return { ok: false, error: `「${module.meta.name}」需要 ${module.meta.minPlayers}–${module.meta.maxPlayers} 人` };
    }
    const config = module.configSchema.safeParse(rawConfig ?? {});
    if (!config.success) return { ok: false, error: "游戏设置无效" };

    const pool = module.meta.contentType ? await this.deps.content.pool(module.meta.contentType, this.sessionId) : [];
    const { ctx, drawn } = this.makeContext(pool);
    const result = module.setup(config.data, ctx);
    if (!result.ok) return { ok: false, error: result.error };

    const seg: LiveSegment = {
      id: newId("seg"),
      gameId,
      module,
      status: "active",
      state: result.state,
      pool,
      offered: new Map(),
    };
    await this.deps.db.transaction(async (tx) => {
      await tx.insert(segments).values({
        id: seg.id,
        sessionId: this.sessionId,
        gameId,
        status: "active",
        config: config.data,
        state: result.state,
      });
      await this.deps.content.recordUsage(tx, this.sessionId, seg.id, drawn);
    });
    this.segment = seg;
    this.suggestion = null;
    this.lastSegment = null;
    this.scheduleDeadline();
    await this.pumpCanvas();
    this.broadcast();
    return { ok: true };
  }

  private makeContext(
    pool: ContentItem[],
    offered: Map<string, ContentItem> = new Map(),
  ): { ctx: GameContext; drawn: ContentItem[] } {
    const drawn: ContentItem[] = [];
    const ctx: GameContext = {
      now: this.now(),
      random: this.deps.random ?? Math.random,
      players: [...this.members.keys()],
      drawContent: () => {
        const item = pool.shift();
        if (item) drawn.push(item);
        return item ?? null;
      },
      // Rotates the pool so the next peek shows different items; nothing is used up.
      peekContent: (count) => {
        const items = pool.splice(0, Math.max(0, count));
        pool.push(...items);
        return items;
      },
      consumeContent: (id) => {
        const index = pool.findIndex((item) => item.id === id);
        const item = index >= 0 ? pool.splice(index, 1)[0] : offered.get(id);
        // Unknown ids (e.g. offered before a restart) are still recorded as used.
        drawn.push(item ?? { id, version: 1, type: "", theme: "", payload: null });
      },
    };
    return { ctx, drawn };
  }

  /** Persists a game result atomically (state + scores + content usage), then updates memory. */
  private async commit(seg: LiveSegment, result: GameResult<unknown>, drawn: ContentItem[]): Promise<Ack> {
    if (!result.ok) {
      seg.pool.unshift(...drawn.filter((d) => d.type));
      return { ok: false, error: result.error };
    }
    let awarded: { playerId: string; points: number }[] = [];
    try {
      awarded = await this.deps.db.transaction(async (tx) => {
        await tx
          .update(segments)
          .set({
            state: result.state,
            ...(result.finished ? { status: "finished" as const, endedAt: new Date() } : {}),
          })
          .where(eq(segments.id, seg.id));
        await this.deps.content.recordUsage(tx, this.sessionId, seg.id, drawn);
        // Content written by players during play joins the library, labelled with its origin.
        for (const c of result.contributed ?? []) {
          const author = this.members.get(c.authorId)?.nickname ?? "玩家";
          const { saved } = await this.deps.content.save(tx, [c], `玩家自拟：${author}`);
          await this.deps.content.recordUsage(tx, this.sessionId, seg.id, saved);
        }
        if (!result.scores?.length) return [];
        // The unique (segment, award key) index makes re-settlement a no-op.
        return tx
          .insert(scoreEvents)
          .values(
            result.scores.map((s) => ({
              id: newId("sc"),
              sessionId: this.sessionId,
              segmentId: seg.id,
              playerId: s.playerId,
              points: s.points,
              reason: s.reason,
              awardKey: s.key,
            })),
          )
          .onConflictDoNothing()
          .returning({ playerId: scoreEvents.playerId, points: scoreEvents.points });
      });
    } catch (err) {
      seg.pool.unshift(...drawn.filter((d) => d.type));
      throw err;
    }
    seg.state = result.state;
    for (const a of awarded) this.scores.set(a.playerId, (this.scores.get(a.playerId) ?? 0) + a.points);
    if (result.finished) {
      await this.closeSegment(seg, "finished");
    } else {
      this.scheduleDeadline();
      await this.pumpCanvas();
      this.broadcast();
    }
    return { ok: true };
  }

  /** Back to the lobby. Confirmed scores stay on the session scoreboard. */
  private async closeSegment(seg: LiveSegment, endedReason: "finished" | "aborted") {
    const rows = await this.deps.db
      .select({ playerId: scoreEvents.playerId, points: sql<number>`sum(${scoreEvents.points})::int` })
      .from(scoreEvents)
      .where(eq(scoreEvents.segmentId, seg.id))
      .groupBy(scoreEvents.playerId);
    this.lastSegment = {
      gameId: seg.gameId,
      gameName: seg.module.meta.name,
      endedReason,
      scores: rows.sort((a, b) => b.points - a.points),
    };
    this.segment = null;
    this.scheduleDeadline();
    await this.pumpCanvas();
    this.broadcast();
  }

  // ----------------------------------------------------------------- canvas

  /** Interactions only open while nobody is in the middle of a formal game action. */
  private atSafePoint(): boolean {
    const seg = this.segment;
    if (!seg) return true;
    return seg.status === "active" && (seg.module.atSafePoint?.(seg.state) ?? false);
  }

  /** Opens the next queued interaction if the screen is free and the game is at a safe point. */
  private async pumpCanvas(): Promise<void> {
    while (this.canvasCurrent?.status !== "open" && this.canvasQueue.length > 0 && this.atSafePoint()) {
      const next = this.canvasQueue.shift() as LiveInteraction;
      // Display-only interactions never wait for anyone: they are shown and immediately complete.
      const displayOnly = next.spec.kind === "show";
      next.status = displayOnly ? "closed" : "open";
      next.result = displayOnly ? computeResult(next) : null;
      await this.deps.db
        .update(interactions)
        .set({ status: next.status, result: next.result, ...(displayOnly ? { closedAt: new Date() } : {}) })
        .where(eq(interactions.id, next.id));
      this.canvasCurrent = next;
    }
  }

  private async enqueueInteraction(spec: InteractionSpec, createdBy: "agent" | "system"): Promise<LiveInteraction> {
    const live: LiveInteraction = { id: newId("int"), spec, status: "queued", responses: {}, result: null, createdBy };
    await this.deps.db
      .insert(interactions)
      .values({ id: live.id, roomId: this.roomId, sessionId: this.sessionId, createdBy, status: "queued", spec });
    this.canvasQueue.push(live);
    await this.pumpCanvas();
    this.broadcast();
    return live;
  }

  /** Closes the open interaction: fixes its result, runs an approved effect, then tells the AI host. */
  private async closeInteraction(live: LiveInteraction): Promise<void> {
    let outcome = "";
    if (live.spec.kind === "confirm") {
      const approved = Object.values(live.responses).some((v) => v === true);
      // The effect was fixed when the confirmation was created; approval executes exactly that.
      outcome = approved ? await this.executeEffect(live.spec.effect) : "没有执行";
    }
    live.result = computeResult(live, outcome);
    live.status = "closed";
    await this.deps.db
      .update(interactions)
      .set({ status: "closed", responses: live.responses, result: live.result, closedAt: new Date() })
      .where(eq(interactions.id, live.id));
    const nameOf = (id: PlayerId) => this.members.get(id)?.nickname ?? "?";
    await this.appendChat({ kind: "system" }, summarize(live, nameOf));
    await this.pumpCanvas();
    this.broadcast();
    if (live.createdBy === "agent") {
      this.deps.agent.trigger(this, {
        kind: "interaction",
        title: live.spec.title,
        result: summarize(live, nameOf, true),
      });
    }
  }

  private async executeEffect(effect: CanvasEffect): Promise<string> {
    switch (effect.type) {
      case "startGame": {
        const ack = await this.startGame(effect.gameId, effect.config);
        return ack.ok ? `已开始「${games[effect.gameId]?.meta.name ?? effect.gameId}」` : `没能开始：${ack.error}`;
      }
    }
  }

  /** Program-written description of an effect, so approvers never rely on the model's wording. */
  private describeEffect(effect: CanvasEffect): string {
    switch (effect.type) {
      case "startGame": {
        const meta = games[effect.gameId]?.meta;
        const settings = (meta?.options ?? [])
          .filter((o) => effect.config[o.key] !== undefined)
          .map((o) => `${o.label} ${effect.config[o.key]}`)
          .join("，");
        return `批准后将立即开始「${meta?.name ?? effect.gameId}」${settings ? `（${settings}）` : "（默认设置）"}`;
      }
    }
  }

  // ----------------------------------------------------------------- timers

  private now(): number {
    return this.deps.now?.() ?? Date.now();
  }

  private scheduleDeadline() {
    if (this.timer) clearTimeout(this.timer);
    this.timer = null;
    const seg = this.segment;
    if (this.disposed || !seg || seg.status !== "active") return;
    const deadline = seg.module.deadline?.(seg.state);
    if (deadline == null) return;
    this.timer = setTimeout(
      () => {
        this.exclusive(() => this.onDeadline(seg.id)).catch((err) =>
          console.error(`[room ${this.roomId}] timeout handling failed:`, err),
        );
      },
      Math.max(0, deadline - this.now()),
    );
    this.timer.unref();
  }

  private async onDeadline(segmentId: string) {
    const seg = this.segment;
    if (!seg || seg.id !== segmentId || seg.status !== "active" || !seg.module.onTimeout) return;
    const deadline = seg.module.deadline?.(seg.state);
    // The state may have moved on since the timer was armed.
    if (deadline == null || deadline > this.now()) return this.scheduleDeadline();
    const { ctx, drawn } = this.makeContext(seg.pool, seg.offered);
    await this.commit(seg, seg.module.onTimeout(structuredClone(seg.state), ctx), drawn);
  }

  // ------------------------------------------------------------------ views

  private scoreboard(): ScoreEntry[] {
    return [...this.members.keys()]
      .map((playerId) => ({ playerId, points: this.scores.get(playerId) ?? 0 }))
      .sort((a, b) => b.points - a.points);
  }

  private viewFor(playerId: PlayerId): RoomView {
    const isHost = playerId === this.hostPlayerId;
    const seg = this.segment;
    return {
      room: { id: this.roomId, name: this.roomName },
      me: { playerId, isHost },
      ...(isHost ? { inviteToken: this.inviteToken } : {}),
      members: [...this.members.values()].map((m) => ({
        id: m.id,
        nickname: m.nickname,
        isHost: m.id === this.hostPlayerId,
        connected: this.isConnected(m.id),
      })),
      sessionId: this.sessionId,
      scoreboard: this.scoreboard(),
      games: Object.values(games).map((g) => g.meta),
      segment: seg
        ? {
            id: seg.id,
            gameId: seg.gameId,
            status: seg.status,
            view: seg.module.view(seg.state, playerId),
            skip: this.skipViewFor(seg, playerId),
            contentId: seg.module.currentContentId?.(seg.state) ?? null,
          }
        : null,
      lastSegment: this.lastSegment,
      suggestion: this.suggestion,
      ai: this.aiStatus,
      canvas: {
        current: this.canvasCurrent
          ? toView(
              this.canvasCurrent,
              playerId,
              [...this.members.keys()],
              this.canvasCurrent.spec.kind === "confirm"
                ? this.describeEffect(this.canvasCurrent.spec.effect)
                : undefined,
            )
          : null,
        queued: this.canvasQueue.length,
      },
    };
  }

  private skipViewFor(seg: LiveSegment, playerId: PlayerId): SegmentView["skip"] {
    const key = seg.status === "active" ? (seg.module.skip?.key(seg.state) ?? null) : null;
    if (!seg.module.skip || key === null) return null;
    // Votes cast for an earlier item never carry over.
    const vote = this.skipVote?.key === key ? this.skipVote : null;
    const voters = vote?.voters ?? seg.module.skip.voters(seg.state);
    return {
      key,
      votes: vote?.votes.size ?? 0,
      needed: Math.floor(voters.length / 2) + 1,
      canVote: voters.includes(playerId),
      voted: vote?.votes.has(playerId) ?? false,
    };
  }

  private broadcast() {
    for (const c of this.connections.values()) c.send(MSG.view, this.viewFor(c.playerId));
  }

  // ------------------------------------------------------- AgentRoomPort

  agentContext(): AgentRoomContext {
    const name = (id: PlayerId) => this.members.get(id)?.nickname ?? "?";
    const lines = [
      `房间「${this.roomName}」，成员：${[...this.members.values()]
        .map(
          (m) =>
            `${m.nickname}${m.id === this.hostPlayerId ? "（房主）" : ""}${this.isConnected(m.id) ? "" : "（离线）"}`,
        )
        .join("、")}`,
      `本场累计积分：${
        this.scoreboard()
          .map((s) => `${name(s.playerId)} ${s.points}`)
          .join("，") || "暂无"
      }`,
      this.segment
        ? `当前游戏${this.segment.status === "paused" ? "（已暂停，等待房主恢复）" : ""}：${this.segment.module.publicSummary(this.segment.state)}`
        : "当前在大厅，没有进行中的游戏。",
    ];
    const seg = this.segment;
    const contentType = seg?.module.meta.contentType;
    const guide = contentType ? contentTypes[contentType]?.guide : undefined;
    const current = this.canvasCurrent;
    return {
      members: [...this.members.values()].map((m) => ({
        id: m.id,
        nickname: m.nickname,
        isHost: m.id === this.hostPlayerId,
      })),
      canvas: [
        current
          ? current.status === "open"
            ? `屏幕上的互动（等待回应）：「${current.spec.title}」`
            : summarize(current, name)
          : "主面板上没有互动。",
        this.canvasQueue.length > 0
          ? `排队中的互动：${this.canvasQueue.map((q) => `「${q.spec.title}」`).join("、")}`
          : "",
      ]
        .filter(Boolean)
        .join("\n"),
      note: this.agentNote,
      content: seg
        ? seg.module.offer && contentType && guide
          ? { gameAcceptsOffers: true, type: contentType, guide }
          : { gameAcceptsOffers: false }
        : null,
      state: lines.join("\n"),
      recentChat: this.chat.slice(-AGENT_CHAT_CONTEXT).map((m) => ({
        speaker: m.sender.kind === "player" ? m.sender.nickname : m.sender.kind === "agent" ? "AI 主持" : "系统",
        text: m.text,
      })),
      games: Object.values(games).map((g) => g.meta),
    };
  }

  suggestGame(gameId: string, reason: string): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const module = games[gameId];
      if (!module) return { ok: false, message: `失败：没有 id 为 ${gameId} 的已实现游戏。` };
      // Checked against the latest state at execution time, not when the model was called.
      if (this.segment) return { ok: false, message: "失败：有游戏正在进行，现在不能发起推荐。" };
      this.suggestion = { gameId, reason };
      this.broadcast();
      return { ok: true, message: `已在主面板展示「${module.meta.name}」的推荐，等待房主决定是否开始（尚未开始）。` };
    });
  }

  createInteraction(spec: AgentInteractionSpec): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const members = [...this.members.keys()];
      if (spec.kind !== "show" && respondersOf(spec, members).length === 0) {
        return { ok: false, message: "失败：指定的回应者都不在房间里（audience 要用成员 id）。" };
      }
      const live = await this.enqueueInteraction(spec, "agent");
      const state =
        live.status === "queued"
          ? "已排队，会在当前回合结束后的间隙显示"
          : spec.kind === "show"
            ? "已展示在主面板"
            : "已显示在主面板，正在等玩家回应";
      return {
        ok: true,
        message: `${state}。${spec.kind === "show" ? "" : "玩家回应完（或房主收尾）后你会收到结果，现在不需要等待。"}`,
      };
    });
  }

  async saveContent(type: string, theme: string, payloads: unknown[]): Promise<{ ok: boolean; message: string }> {
    const { saved, rejected } = await this.deps.content.save(
      this.deps.db,
      payloads.map((payload) => ({ type, theme, payload })),
      `AI 生成（${this.deps.agent.modelLabel}）`,
    );
    const parts = [
      saved.length > 0 ? `已保存 ${saved.length} 条，id：${saved.map((i) => i.id).join(", ")}` : "没有保存任何内容",
      ...rejected,
    ];
    return { ok: saved.length > 0, message: parts.join("。") };
  }

  offerContent(ids: string[]): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const seg = this.segment;
      if (!seg) return { ok: false, message: "失败：现在没有进行中的游戏，候选内容只能交给进行中的游戏。" };
      if (seg.status === "paused") return { ok: false, message: "失败：游戏已暂停。" };
      if (!seg.module.offer) return { ok: false, message: `失败：「${seg.module.meta.name}」不接受外部候选内容。` };
      const items = await this.deps.content.getByIds(ids);
      if (items.length === 0) return { ok: false, message: "失败：题库里找不到这些 id。" };
      const { ctx, drawn } = this.makeContext(seg.pool, seg.offered);
      const result = seg.module.offer(structuredClone(seg.state), items, ctx);
      if (!result.ok) return { ok: false, message: `失败：${result.error}` };
      for (const item of items) seg.offered.set(item.id, item);
      const ack = await this.commit(seg, result, drawn);
      return ack.ok
        ? { ok: true, message: result.message ?? "已交给游戏" }
        : { ok: false, message: `失败：${ack.error}` };
    });
  }

  proposeStartGame(
    gameId: string,
    config: Record<string, number>,
    reason: string,
  ): Promise<{ ok: boolean; message: string }> {
    return this.exclusive(async () => {
      const module = games[gameId];
      if (!module) return { ok: false, message: `失败：没有 id 为 ${gameId} 的已实现游戏。` };
      const parsed = module.configSchema.safeParse(config);
      if (!parsed.success) return { ok: false, message: "失败：设置项无效（只能用该游戏列出的设置键和范围）。" };
      await this.enqueueInteraction(
        {
          kind: "confirm",
          title: `开始「${module.meta.name}」？`,
          description: reason.slice(0, 200),
          audience: [this.hostPlayerId],
          effect: { type: "startGame", gameId, config },
        },
        "agent",
      );
      return { ok: true, message: "已向房主发出确认请求（尚未开始）。房主决定后你会收到结果。" };
    });
  }

  async setNote(text: string): Promise<void> {
    this.agentNote = text.slice(0, 600) || null;
    await this.deps.db.update(rooms).set({ agentNote: this.agentNote }).where(eq(rooms.id, this.roomId));
  }

  postChat(kind: "agent" | "system", text: string): Promise<void> {
    return this.appendChat({ kind }, text);
  }

  setAiStatus(status: AiStatus) {
    this.aiStatus = status;
    this.broadcast();
  }
}
